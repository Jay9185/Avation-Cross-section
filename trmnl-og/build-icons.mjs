// Dev-only: turns the SVG icon symbols in ../full.liquid into flattened polygons (icons.js) so the Worker
// can fill them straight into a bitmap. It also copies the type -> icon tables and airline map from ../worker.js
// verbatim, so the OG uses exactly the same icon choices as the TRMNL X plugin.
//   npm i svgpath (anywhere) ; node build-icons.mjs
import { readFileSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
const require = createRequire(process.env.SVGPATH_FROM || '/home/claude/build-tmp/');
const svgpath = require('svgpath');

const liquid = readFileSync('../full.liquid', 'utf8');
const src = readFileSync('../worker.js', 'utf8');

function dp(pts, eps) { // Douglas-Peucker on an open polyline
  if (pts.length < 3) return pts;
  const keep = new Uint8Array(pts.length); keep[0] = keep[pts.length - 1] = 1;
  const st = [[0, pts.length - 1]];
  while (st.length) {
    const [a, b] = st.pop(); let dmax = 0, idx = -1;
    const [x1, y1] = pts[a], [x2, y2] = pts[b], dx = x2 - x1, dy = y2 - y1, L = Math.hypot(dx, dy) || 1e-9;
    for (let i = a + 1; i < b; i++) { const d = Math.abs(dy * pts[i][0] - dx * pts[i][1] + x2 * y1 - y2 * x1) / L; if (d > dmax) { dmax = d; idx = i; } }
    if (dmax > eps) { keep[idx] = 1; st.push([a, idx], [idx, b]); }
  }
  return pts.filter((_, i) => keep[i]);
}
function simplifyRing(r, eps) { // r is closed (first == last); split at the farthest point so DP has two real halves
  const pts = r.slice(0, -1);
  let k = 0, best = 0;
  for (let i = 1; i < pts.length; i++) { const d = Math.hypot(pts[i][0] - pts[0][0], pts[i][1] - pts[0][1]); if (d > best) { best = d; k = i; } }
  if (!k) return pts;
  const a = dp(pts.slice(0, k + 1), eps), b = dp([...pts.slice(k), pts[0]], eps);
  return [...a.slice(0, -1), ...b.slice(0, -1)];
}
const area = (r) => { let s = 0; for (let i = 0; i < r.length; i++) { const [x1, y1] = r[i], [x2, y2] = r[(i + 1) % r.length]; s += x1 * y2 - x2 * y1; } return s / 2; };

const out = {};
for (const [, id, vb, body] of liquid.matchAll(/<symbol id="s-([^"]+)" viewBox="([^"]+)">(.*?)<\/symbol>/gs)) {
  const d = body.match(/ d="([^"]+)"/)[1];
  const rule = /evenodd/.test(body) ? 'evenodd' : 'nonzero';
  const [vx, vy, vw, vh] = vb.split(/\s+/).map(Number);
  const eps = (0.3 * Math.max(vw, vh)) / 50;
  const p = svgpath(d).abs().unarc().unshort();
  const rings = []; let cur = [], cx = 0, cy = 0, sx = 0, sy = 0;
  const flush = () => { if (cur.length > 2) rings.push(cur); cur = []; };
  p.iterate((seg) => {
    const c = seg[0];
    if (c === 'M') { flush(); cx = sx = seg[1]; cy = sy = seg[2]; cur = [[cx, cy]]; }
    else if (c === 'L') { cx = seg[1]; cy = seg[2]; cur.push([cx, cy]); }
    else if (c === 'H') { cx = seg[1]; cur.push([cx, cy]); }
    else if (c === 'V') { cy = seg[1]; cur.push([cx, cy]); }
    else if (c === 'C') {
      const [x1, y1, x2, y2, x3, y3] = seg.slice(1);
      const n = Math.max(3, Math.ceil(Math.hypot(x3 - cx, y3 - cy) / (eps * 2)) + 1);
      for (let i = 1; i <= Math.min(n, 12); i++) { const t = i / Math.min(n, 12), u = 1 - t; cur.push([u*u*u*cx + 3*u*u*t*x1 + 3*u*t*t*x2 + t*t*t*x3, u*u*u*cy + 3*u*u*t*y1 + 3*u*t*t*y2 + t*t*t*y3]); }
      cx = x3; cy = y3;
    } else if (c === 'Q') {
      const [x1, y1, x2, y2] = seg.slice(1);
      for (let i = 1; i <= 6; i++) { const t = i / 6, u = 1 - t; cur.push([u*u*cx + 2*u*t*x1 + t*t*x2, u*u*cy + 2*u*t*y1 + t*t*y2]); }
      cx = x2; cy = y2;
    } else if (c === 'Z') { cur.push([sx, sy]); cx = sx; cy = sy; flush(); }
  });
  flush();
  const simp = rings.map((r) => simplifyRing(r, eps).map((q) => [+q[0].toFixed(2), +q[1].toFixed(2)]))
    .filter((r) => r.length >= 3 && Math.abs(area(r)) > eps * eps * 0.5);
  out[id] = { vb: [vx, vy, vw, vh], rule, rings: simp };
}

const cut = (a, b) => { const i = src.indexOf(a), j = src.indexOf(b); if (i < 0 || j < 0) throw new Error(`marker missing: ${a} / ${b}`); return src.slice(i, j); };
const iconBlock = cut('const SHAPES =', 'const CARGO =');
const airlineBlock = cut('const AIRLINE_MAP =', 'const JSON_HEADERS');
const airlineFn = src.slice(src.indexOf('function getAirlineFromCallsign'));

const js = `// Aircraft silhouettes: tar1090 (GPL-3.0) https://github.com/wiedehopf/tar1090
// GENERATED by build-icons.mjs from ../full.liquid and ../worker.js. Do not edit by hand.
export const POLYS = ${JSON.stringify(out)};

${iconBlock}
${airlineBlock}
${airlineFn.replace(/\n+$/, '\n')}
export { SHAPES, resolveIcon, AIRLINE_MAP, getAirlineFromCallsign };
`;
writeFileSync('icons.js', js);
let pts = 0; for (const k in out) for (const r of out[k].rings) pts += r.length;
console.log(`${Object.keys(out).length} icons, ${pts} points, icons.js ${(js.length / 1024).toFixed(1)} KB`);
