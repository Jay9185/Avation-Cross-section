# Dev-only: bakes Liberation Sans (Arial-metric, SIL OFL) into 1-bit glyph bitmaps -> font.js
import json
from PIL import Image, ImageDraw, ImageFont
D='/usr/share/fonts/truetype/liberation/'
STY={'b':D+'LiberationSans-Bold.ttf','r':D+'LiberationSans-Regular.ttf'}
SIZES={'b':[8,9,10,11,12,13,14,20,26],'r':[8,9,10,11,12]}
CH="ABCDEFGHIJKLMNOPQRSTUVWXYZ0123456789 -:./+kt"
out={}
for s,p in STY.items():
    for z in SIZES[s]:
        f=ImageFont.truetype(p,z); asc,desc=f.getmetrics()
        g={}
        for c in CH:
            adv=round(f.getlength(c))
            if c==' ': g[c]=[adv,0,0,0,'']; continue
            l,t,r,b=f.getbbox(c,anchor='ls')
            w,h=r-l,b-t
            im=Image.new('1',(w+4,h+4),0); d=ImageDraw.Draw(im); d.fontmode='1'
            d.text((2-l,2-t),c,font=f,fill=1,anchor='ls')
            rows=[''.join('1' if im.getpixel((x+2,y+2)) else '0' for x in range(w)) for y in range(h)]
            g[c]=[adv,l,t,w,','.join(rows)]
        out[f'{s}{z}']={'a':asc,'h':asc+desc,'g':g}
open('font.js','w').write('// Generated by build-font.py from Liberation Sans (SIL OFL 1.1).\nexport const FONTS = '+json.dumps(out,separators=(',',':'))+';\n')
